"""Prepare a standard XCTest run for an already-installed iOS app and runner."""

from __future__ import annotations

import argparse
import json
import plistlib
import subprocess
from pathlib import Path
from typing import Any
from uuid import UUID

APP_ID = 'com.yowamushi-inc.RideIntercom.RideIntercom'
RUNNER_ID = 'com.yowamushi-inc.RideIntercom.RideIntercomUITests.xctrunner'
RUNNER_PATH = '__TESTROOT__/Debug-Validation-iphoneos/RideIntercomUITests-Runner.app'
APP_PATH = '__TESTROOT__/Debug-Validation-iphoneos/RideIntercom.app'
TEST_BUNDLE = '__TESTHOST__/PlugIns/RideIntercomUITests.xctest'
SELECTOR = 'BackgroundCallLifecycleUITests/testStartInvitedTrialGroupMuted'


def read_device_info(device: str, command: str, *options: str) -> dict[str, Any]:
    try:
        output = subprocess.run(
            ['xcrun', 'devicectl', 'device', 'info', command, '--device', device, *options,
             '--timeout', '8', '--json-output', '-'],
            capture_output=True, check=True, timeout=10,
        )
        document = json.loads(output.stdout)
    except (OSError, ValueError, subprocess.SubprocessError):
        return {}
    result = document.get('result') if isinstance(document, dict) else None
    return result if isinstance(result, dict) else {}


def check_device(device: str) -> tuple[dict[str, str | None], int]:
    inventory = read_device_info(
        device, 'apps', '--include-all-apps', '--filter',
        f"bundleIdentifier IN {{'{APP_ID}', '{RUNNER_ID}'}}",
    ).get('apps')
    passcode_required = read_device_info(device, 'lockState').get('passcodeRequired')
    processes = read_device_info(device, 'processes', '--search', 'RideIntercom.app/RideIntercom').get('runningProcesses')
    report = {'app': 'unknown', 'app_build': None, 'runner': 'unknown', 'lock': 'unknown', 'process': 'unknown'}
    if isinstance(inventory, list) and all(
        isinstance(app, dict) and isinstance(app.get('bundleIdentifier'), str) for app in inventory
    ):
        apps = {app['bundleIdentifier']: app for app in inventory}
        report['app'] = 'installed' if APP_ID in apps else 'missing'
        report['runner'] = 'installed' if RUNNER_ID in apps else 'missing'
        build = apps.get(APP_ID, {}).get('bundleVersion')
        if isinstance(build, str) and build.isascii() and build.isdecimal() and len(build) <= 12:
            report['app_build'] = build
    if isinstance(passcode_required, bool):
        report['lock'] = 'locked' if passcode_required else 'unlocked'
    if isinstance(processes, list) and all(isinstance(process, dict) for process in processes):
        report['process'] = 'running' if processes else 'absent'
    if 'unknown' in report.values():
        return report, 2
    return report, 1 if 'missing' in report.values() else 0


def prepare(source: Path, destination: Path, trial_id: UUID) -> None:
    with source.open('rb') as stream:
        plan = plistlib.load(stream)
    configurations = plan['TestConfigurations']
    if len(configurations) != 1 or not configurations[0]['IsEnabled']:
        raise ValueError('Expected one enabled shared scheme test configuration')
    configuration = configurations[0]
    ui_targets = [target for target in configuration['TestTargets'] if target.get('IsUITestBundle') is True]
    if len(ui_targets) != 1:
        raise ValueError('Expected one iOS UI test target')
    target = ui_targets[0]
    if (target.get('BlueprintName'), target.get('TestHostBundleIdentifier'), target.get('TestHostPath'),
            target.get('TestBundlePath'), target.get('UITargetAppPath')) != (
            'RideIntercomUITests', RUNNER_ID, RUNNER_PATH, TEST_BUNDLE, APP_PATH):
        raise ValueError('Expected the generated iPhoneOS plan for RideIntercom')

    configuration['TestTargets'] = [target]
    for key in ('TestHostPath', 'TestBundlePath', 'UITargetAppPath', 'DependentProductPaths',
                'UITargetAppEnvironmentVariables', 'UITargetAppCommandLineArguments', 'SkipTestIdentifiers'):
        target.pop(key, None)
    target.update(UseDestinationArtifacts=True, TestBundleDestinationRelativePath=TEST_BUNDLE,
                  UITargetAppBundleIdentifier=APP_ID, OnlyTestIdentifiers=[SELECTOR],
                  EnvironmentVariables={'RIDEINTERCOM_INSTALLED_TRIAL_ID': str(trial_id)},
                  SystemAttachmentLifetime='keepNever', UserAttachmentLifetime='keepNever')
    plan.pop('CodeCoverageBuildableInfos', None)
    with destination.open('xb') as stream:
        plistlib.dump(plan, stream)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check-device', metavar='DESTINATION',
                        help='read the installed bundles, lock state, and RideCom process via Xcode')
    parser.add_argument('source', nargs='?', type=Path, help='iPhoneOS xctestrun generated by RideIntercom build-for-testing')
    parser.add_argument('destination', nargs='?', type=Path, help='new xctestrun to create')
    parser.add_argument('trial_id', nargs='?', type=UUID, help='non-secret UUID identifying the test group for this run')
    args = parser.parse_args()
    plan_args = (args.source, args.destination, args.trial_id)
    if args.check_device is not None:
        if any(value is not None for value in plan_args):
            parser.error('--check-device is separate from test plan generation')
        report, status = check_device(args.check_device)
        print(json.dumps(report))
        parser.exit(status)
    if any(value is None for value in plan_args):
        parser.error('expected source, destination, and trial_id, or --check-device')
    try:
        prepare(args.source, args.destination, args.trial_id)
    except (OSError, ValueError, KeyError, TypeError, plistlib.InvalidFileException):
        parser.exit(2, 'Cannot prepare the installed-app test plan. Check the iPhoneOS source and new destination.\n')


if __name__ == '__main__':
    main()
