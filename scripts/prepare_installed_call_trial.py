"""Prepare a standard XCTest run for an already-installed iOS app and runner."""

import argparse
import plistlib
from pathlib import Path
from uuid import UUID

APP_ID = 'com.yowamushi-inc.RideIntercom.RideIntercom'
RUNNER_ID = 'com.yowamushi-inc.RideIntercom.RideIntercomUITests.xctrunner'
RUNNER_PATH = '__TESTROOT__/Debug-Validation-iphoneos/RideIntercomUITests-Runner.app'
APP_PATH = '__TESTROOT__/Debug-Validation-iphoneos/RideIntercom.app'
TEST_BUNDLE = '__TESTHOST__/PlugIns/RideIntercomUITests.xctest'
SELECTOR = 'BackgroundCallLifecycleUITests/testStartInvitedTrialGroupMuted'


def prepare(source: Path, destination: Path, trial_id: UUID) -> None:
    with source.open('rb') as stream:
        plan = plistlib.load(stream)
    configurations = plan['TestConfigurations']
    if len(configurations) != 1 or not configurations[0]['IsEnabled']:
        raise ValueError('Expected one enabled shared scheme test configuration')
    configuration = configurations[0]
    ui_targets = [target for target in configuration['TestTargets'] if target.get('IsUITestBundle') is True]
    if len(ui_targets) != 1:
        raise ValueError('Expected one iOS UI test target')
    target = ui_targets[0]
    if (target.get('BlueprintName'), target.get('TestHostBundleIdentifier'), target.get('TestHostPath'),
            target.get('TestBundlePath'), target.get('UITargetAppPath')) != (
            'RideIntercomUITests', RUNNER_ID, RUNNER_PATH, TEST_BUNDLE, APP_PATH):
        raise ValueError('Expected the generated iPhoneOS plan for RideIntercom')

    configuration['TestTargets'] = [target]
    for key in ('TestHostPath', 'TestBundlePath', 'UITargetAppPath', 'DependentProductPaths',
                'UITargetAppEnvironmentVariables', 'UITargetAppCommandLineArguments', 'SkipTestIdentifiers'):
        target.pop(key, None)
    target.update(UseDestinationArtifacts=True, TestBundleDestinationRelativePath=TEST_BUNDLE,
                  UITargetAppBundleIdentifier=APP_ID, OnlyTestIdentifiers=[SELECTOR],
                  EnvironmentVariables={'RIDEINTERCOM_INSTALLED_TRIAL_ID': str(trial_id)},
                  SystemAttachmentLifetime='keepNever', UserAttachmentLifetime='keepNever')
    plan.pop('CodeCoverageBuildableInfos', None)
    with destination.open('xb') as stream:
        plistlib.dump(plan, stream)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='iPhoneOS xctestrun generated by RideIntercom build-for-testing')
    parser.add_argument('destination', type=Path, help='new xctestrun to create')
    parser.add_argument('trial_id', type=UUID, help='non-secret UUID identifying the test group for this run')
    args = parser.parse_args()
    try:
        prepare(args.source, args.destination, args.trial_id)
    except (OSError, ValueError, KeyError, TypeError, plistlib.InvalidFileException):
        parser.exit(2, 'Cannot prepare the installed-app test plan. Check the iPhoneOS source and new destination.\n')


if __name__ == '__main__':
    main()
